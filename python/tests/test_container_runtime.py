"""Container runtime tests: they start the real image.

These tests need Docker and an image built from the repository, by default `aigov-core:hardened`
(override with AIGOV_TEST_IMAGE). Without Docker they skip. CI sets AIGOV_REQUIRE_CONTAINER_TESTS=1,
which turns every skip into a failure, so a missing runtime cannot pass silently.

Keys and bundles are disposable, generated by `scripts/staging_policy_verify.py prepare`. Nothing
here touches production, and nothing is written outside the repository's artifacts directory.
"""

from __future__ import annotations

import json
import os
import secrets
import shutil
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
IMAGE = os.environ.get("AIGOV_TEST_IMAGE", "aigov-core:hardened")
REQUIRE = os.environ.get("AIGOV_REQUIRE_CONTAINER_TESTS") == "1"
MOUNT_BASE = REPO_ROOT / "artifacts" / "container-tests"
PG_IMAGE = os.environ.get("AIGOV_TEST_PG_IMAGE", "postgres:16-alpine")


def _skip(reason: str) -> None:
    if REQUIRE:
        pytest.fail(f"container tests required but unavailable: {reason}")
    pytest.skip(reason)


def _docker(
    *args: str, timeout: int = 120, check: bool = False
) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["docker", *args], capture_output=True, text=True, timeout=timeout, check=check
    )


@pytest.fixture(scope="session", autouse=True)
def _require_image() -> None:
    try:
        ok = (
            _docker("version", "--format", "{{.Server.Version}}", timeout=20).returncode
            == 0
        )
    except (OSError, subprocess.TimeoutExpired):
        ok = False
    if not ok:
        _skip("Docker is not available")
    if _docker("image", "inspect", IMAGE).returncode != 0:
        _skip(f"image {IMAGE} is not built; run `docker build --no-cache -t {IMAGE} .`")


def _run_once(*args: str, timeout: int = 120) -> subprocess.CompletedProcess:
    return _docker("run", "--rm", *args, timeout=timeout)


def _mount_dir(prefix: str) -> Path:
    # Docker Desktop shares only some host paths; use the repository's git-ignored artifacts directory.
    MOUNT_BASE.mkdir(parents=True, exist_ok=True)
    d = MOUNT_BASE / f"{prefix}{secrets.token_hex(4)}"
    d.mkdir()
    return d


@pytest.fixture(scope="session")
def fixtures() -> Path:
    """Disposable signed bundle, trust store, and negative fixtures (see staging_policy_verify.py prepare)."""
    out = _mount_dir("fixtures-")
    proc = subprocess.run(
        [
            sys.executable,
            str(REPO_ROOT / "scripts" / "staging_policy_verify.py"),
            "prepare",
            "--out-dir",
            str(out / "bundle"),
        ],
        capture_output=True,
        text=True,
        timeout=120,
        check=False,
    )
    if proc.returncode != 0:
        _skip(f"fixture preparation failed: {proc.stderr.strip()[-300:]}")
    yield out / "bundle"
    shutil.rmtree(out, ignore_errors=True)


