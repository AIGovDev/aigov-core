def test_runs_as_non_root_user():
    proc = _run_once("--entrypoint", "id", IMAGE)
    assert proc.returncode == 0, proc.stderr
    assert "uid=1000(govai)" in proc.stdout, proc.stdout


def test_image_contains_no_source_tests_migrations_or_legacy_policy_files():
    script = (
        "set -e; "
        'for p in /build /app/migrations /build/migrations; do [ ! -e "$p" ] || { echo "present: $p"; exit 1; }; done; '
        "find / -xdev \\( -name '*.rs' -o -name 'Cargo.toml' -o -name 'Cargo.lock' \\) "
        "-not -path '/proc/*' 2>/dev/null | head -1 | grep -q . && { echo 'source present'; exit 1; } || true; "
        "[ -z \"$(ls /app/policies 2>/dev/null)\" ] || { echo 'policy files present'; ls /app/policies; exit 1; }; "
        "echo clean"
    )
    proc = _run_once("--entrypoint", "sh", IMAGE, "-c", script)
    assert proc.returncode == 0 and "clean" in proc.stdout, proc.stdout + proc.stderr


def test_image_contains_no_compilers_or_build_tools():
    script = 'for t in cargo rustc gcc cc make; do command -v $t >/dev/null 2>&1 && { echo "present: $t"; exit 1; }; done; echo none'
    proc = _run_once("--entrypoint", "sh", IMAGE, "-c", script)
    assert proc.returncode == 0 and "none" in proc.stdout, proc.stdout + proc.stderr


def test_binary_has_no_unresolved_shared_libraries():
    proc = _run_once("--entrypoint", "sh", IMAGE, "-c", "ldd /app/aigov_audit")
    assert proc.returncode == 0, proc.stderr
    assert "not found" not in proc.stdout, proc.stdout


def test_healthcheck_is_configured():
    proc = _docker(
        "image", "inspect", "--format", "{{json .Config.Healthcheck}}", IMAGE
    )
    assert proc.returncode == 0
    hc = json.loads(proc.stdout)
    assert hc and hc.get("Test"), proc.stdout


