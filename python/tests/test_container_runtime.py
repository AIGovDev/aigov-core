# --- Read-only start, migrations, readiness against a real Postgres ---------------------------


def _wait(url: str, timeout_s: float = 90.0) -> int:
    deadline = time.time() + timeout_s
    last = 0
    while time.time() < deadline:
        try:
            with urllib.request.urlopen(url, timeout=3) as r:
                return r.status
        except urllib.error.HTTPError as e:
            last = e.code
        except (urllib.error.URLError, OSError):
            last = 0
        time.sleep(1)
    return last


@pytest.fixture(scope="module")
def stack(fixtures: Path):
    """Postgres plus the service, read-only, with a valid signed bundle and auto-migrate enabled."""
    suffix = secrets.token_hex(4)
    net = f"aigov-ct-{suffix}"
    pg = f"aigov-ct-pg-{suffix}"
    app = f"aigov-ct-app-{suffix}"
    ledger = f"aigov-ct-ledger-{suffix}"
    pw = secrets.token_urlsafe(16)
    trust = (fixtures / "trust.json").read_text(encoding="utf-8").strip()
    bundle_dir = _mount_dir("live-")
    shutil.copy(
        fixtures / "policy.bundle.staging.json",
        bundle_dir / "policy.bundle.staging.json",
    )
    created = []
    try:
        assert _docker("network", "create", net).returncode == 0
        created.append(("network", net))
        assert (
            _docker(
                "run",
                "-d",
                "--name",
                pg,
                "--network",
                net,
                "-e",
                "POSTGRES_DB=govai",
                "-e",
                "POSTGRES_USER=govai",
                "-e",
                f"POSTGRES_PASSWORD={pw}",
                PG_IMAGE,
            ).returncode
            == 0
        )
        created.append(("container", pg))
        for _ in range(60):
            if (
                _docker(
                    "exec", pg, "pg_isready", "-U", "govai", "-d", "govai"
                ).returncode
                == 0
            ):
                break
            time.sleep(1)
        else:
            pytest.fail("postgres did not become ready")

        assert _docker("volume", "create", ledger).returncode == 0
        created.append(("volume", ledger))
        proc = _docker(
            "run",
            "-d",
            "--name",
            app,
            "--network",
            net,
            "--read-only",
            "--tmpfs",
            "/tmp:rw,noexec,nosuid,size=64m",
            "--cap-drop",
            "ALL",
            "--security-opt",
            "no-new-privileges:true",
            "-v",
            f"{ledger}:/var/lib/govai/ledger",
            "-v",
            f"{bundle_dir}:/app/policies:ro",
            "-p",
            "127.0.0.1::8088",
            "-e",
            "AIGOV_ENVIRONMENT=staging",
            "-e",
            "AIGOV_POLICY_BUNDLE_FILE=/app/policies/policy.bundle.staging.json",
            "-e",
            f"AIGOV_POLICY_TRUST_ED25519_JSON={trust}",
            "-e",
            "GOVAI_AUTO_MIGRATE=true",
            "-e",
            f"DATABASE_URL=postgres://govai:{pw}@{pg}:5432/govai",
            "-e",
            "GOVAI_API_KEYS=ct-key",
            "-e",
            'GOVAI_API_KEYS_JSON={"ct-key":"tenant-ct"}',
            IMAGE,
        )
        assert proc.returncode == 0, proc.stderr
        created.append(("container", app))
        port_line = _docker("port", app, "8088/tcp").stdout.strip().splitlines()
        assert port_line, "service port not published"
        host_port = port_line[0].rsplit(":", 1)[1]
        base = f"http://127.0.0.1:{host_port}"
        yield {
            "base": base,
            "app": app,
            "pg": pg,
            "pw": pw,
            "net": net,
            "ledger": ledger,
        }
    finally:
        for kind, name in reversed(created):
            if kind == "container":
                _docker("rm", "-f", name)
            elif kind == "volume":
                _docker("volume", "rm", "-f", name)
            elif kind == "network":
                _docker("network", "rm", name)
        shutil.rmtree(bundle_dir, ignore_errors=True)


def test_read_only_service_starts_and_reports_ready(stack):
    assert _wait(f"{stack['base']}/health") == 200
    assert _wait(f"{stack['base']}/ready") == 200


def test_root_filesystem_is_read_only(stack):
    proc = _docker(
        "exec", stack["app"], "sh", "-c", "touch /app/should-fail 2>&1; echo rc=$?"
    )
    text = proc.stdout + proc.stderr
    assert "rc=0" not in text, "root filesystem must not be writable"


def test_migrations_applied_once_and_match_embedded_count(stack):
    expected = len(
        [p for p in (REPO_ROOT / "rust" / "migrations").iterdir() if p.suffix == ".sql"]
    )
    proc = _docker(
        "exec",
        stack["pg"],
        "psql",
        "-U",
        "govai",
        "-d",
        "govai",
        "-tAc",
        "select count(*) from _sqlx_migrations where success",
    )
    assert proc.returncode == 0, proc.stderr
    assert int(proc.stdout.strip()) == expected, proc.stdout


def test_restart_keeps_migrations_and_readiness(stack):
    assert _docker("restart", stack["app"], timeout=60).returncode == 0
    # `docker restart` can assign a new random host port, so re-read the published port.
    port_line = _docker("port", stack["app"], "8088/tcp").stdout.strip().splitlines()
    assert port_line, "service port not published after restart"
    base = f"http://127.0.0.1:{port_line[0].rsplit(':', 1)[1]}"
    assert _wait(f"{base}/ready") == 200
    proc = _docker(
        "exec",
        stack["pg"],
        "psql",
        "-U",
        "govai",
        "-d",
        "govai",
        "-tAc",
        "select count(*) from _sqlx_migrations where success",
    )
    assert proc.returncode == 0
    assert int(proc.stdout.strip()) == len(
        [p for p in (REPO_ROOT / "rust" / "migrations").iterdir() if p.suffix == ".sql"]
    )


def test_readiness_does_not_write_to_the_ledger(stack):
    """Regression: /ready must not create or delete ledger files (it previously wrote a probe file)."""
    listing = [
        "docker",
        "exec",
        stack["app"],
        "sh",
        "-c",
        "ls -la /var/lib/govai/ledger | sort",
    ]

    def snapshot() -> str:
        proc = _docker(*listing[1:])
        assert proc.returncode == 0, proc.stderr
        return proc.stdout

    before = snapshot()
    for _ in range(5):
        assert _wait(f"{stack['base']}/ready", timeout_s=10) == 200
    assert snapshot() == before, "readiness changed the ledger directory"
